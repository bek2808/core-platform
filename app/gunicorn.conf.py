"""Настройки gunicorn - веб-сервера, который запускает Django в контейнере."""

# Слушать все адреса внутри контейнера; наружу порт открывает только Podman
# (PublishPort=127.0.0.1:8000:8000 в quadlet/core-web.container).
bind = "0.0.0.0:8000"

# 3 рабочих процесса: хватает на ~20 сотрудников и укладывается в лимит памяти.
workers = 3

# Запрос дольше 60 секунд прерывается (защита от зависаний).
timeout = 60
graceful_timeout = 30

# Служебные файлы рабочих процессов - в оперативной памяти: файловая система
# контейнера доступна только для чтения.
worker_tmp_dir = "/dev/shm"

# Управляющий сокет gunicorn (утилита gunicornc, с версии 25.1) отключён:
# приложением управляют systemd и Podman, а сокету негде жить - файловая
# система контейнера только для чтения.
control_socket_disable = True

# Журналы запросов и ошибок - в стандартный вывод (их собирает journald).
accesslog = "-"
errorlog = "-"
loglevel = "info"
