"""
Модель пользователя Core-системы.

Пока она совпадает со стандартной моделью Django (логин, ФИО, e-mail, пароль,
группы и права). Своя модель заведена с самого начала намеренно: потом в неё
можно добавлять поля (филиал, должность, страховая компания для мультиарендности)
без болезненной миграции.
"""
from django.contrib.auth.models import AbstractUser


class User(AbstractUser):
    class Meta:
        verbose_name = "пользователь"
        verbose_name_plural = "пользователи"
