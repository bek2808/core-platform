"""
Приведение введённых значений к единому виду.

Данные приходят от людей и от провайдера ЕРСП с «мусором»: пробелы в конце
(«12-uy  »), двойные пробелы внутри («Choʻlpon MFY,  Elbek»), неразрывные
пробелы из Word и Excel, телефон в виде «+998 (99) 894-44-40». Эти функции
убирают мусор, но не меняют смысл.

Отдельно - ключ для поиска (search_key). Провайдер смешивает в одном слове
кириллицу и латиницу: в «Hаyotni» буква «а» кириллическая, хотя выглядит
как латинская. Человек, который ищет «hayotni» латиницей, такую запись
не нашёл бы. Поэтому для поиска хранится копия, в которой одинаковые
на вид буквы сведены к одной, апострофы и кавычки унифицированы.
Сама карточка хранится как пришла (только без лишних пробелов).
"""
import re

_SPACES = re.compile(r"\s+")
_NOT_DIGITS = re.compile(r"\D")

# Кириллические буквы, которые выглядят как латинские (после перевода
# в нижний регистр). Сводятся к латинским - и в записи, и в запросе.
_LOOKALIKES = str.maketrans(
    {
        "а": "a", "в": "b", "е": "e", "ё": "e", "к": "k", "м": "m", "н": "h",
        "о": "o", "р": "p", "с": "c", "т": "t", "у": "y", "х": "x",
    }
)
# Узбекские апострофы бывают разными символами: oʻ, o', o`, o‘, o’.
_APOSTROPHES = re.compile(r"[ʻʼ`‘’´]")
# Кавычки при поиске не нужны: '"INSON" AJ' ищется по «inson aj».
_QUOTES = re.compile(r"[\"«»“”„]")


def squash_spaces(value):
    """Пробелы по краям убрать, подряд идущие пробелы внутри заменить одним."""
    if value is None:
        return value
    return _SPACES.sub(" ", value).strip()


def remove_spaces(value):
    """Убрать все пробелы: для кодов и номеров (МФО, ИНН, счёт)."""
    if value is None:
        return value
    return _SPACES.sub("", value)


def digits_only(value):
    """Оставить только цифры: «+998 (99) 894-44-40» -> «998998944440»."""
    if value is None:
        return value
    return _NOT_DIGITS.sub("", value)


def search_key(*parts):
    """Ключ для поиска из нескольких значений (названия, ИНН)."""
    text = " ".join(p for p in parts if p)
    text = text.lower().translate(_LOOKALIKES)
    text = _APOSTROPHES.sub("'", text)
    text = _QUOTES.sub("", text)
    return squash_spaces(text)
